package es.us.dp1.chess.tournament.practice.x.inheritance;

import static org.junit.jupiter.api.Assertions.*;

import java.lang.reflect.Field;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.orm.jpa.DataJpaTest;

import es.us.dp1.chess.tournament.ReflexiveTest;
import es.us.dp1.chess.tournament.model.NamedEntity;
import es.us.dp1.chess.tournament.model.Person;
import jakarta.persistence.EntityManager;
import jakarta.validation.Validation;
import jakarta.validation.Validator;

@DataJpaTest
public class TestX38 extends ReflexiveTest {

    @Autowired
    EntityManager em;

    Validator v = Validation.buildDefaultValidatorFactory().getValidator();

    @Test
    public void testX38TheyExtendTheMappedSuperclasses() {
        assertEquals(Person.class, Instructor.class.getSuperclass(), "Instructor must extend Person");
        assertEquals(NamedEntity.class, Studio.class.getSuperclass(), "Studio must extend NamedEntity");
        for (Field f : Instructor.class.getDeclaredFields())
            assertFalse(f.getName().equals("id") || f.getName().equals("firstName") || f.getName().equals("lastName"),
                    "Instructor must not redeclare the inherited attribute " + f.getName());
        for (Field f : Studio.class.getDeclaredFields())
            assertFalse(f.getName().equals("id") || f.getName().equals("name"),
                    "Studio must not redeclare the inherited attribute " + f.getName());
    }

    @Test
    public void testX38InstructorConstraints() {
        Object i = new Instructor();
        Setters.set(i, "firstName", "Judit");
        Setters.set(i, "lastName", "Polgar");
        Setters.set(i, "specialty", "Attack");
        assertTrue(v.validate(i).isEmpty());
        Setters.set(i, "specialty", "  ");
        assertFalse(v.validate(i).isEmpty(), "A blank specialty must be invalid");
        Setters.set(i, "specialty", "Attack");
        Setters.set(i, "firstName", "");
        assertFalse(v.validate(i).isEmpty(), "The inherited constraint of firstName must apply");
    }

    @Test
    public void testX38StudioConstraintsAndPersistence() {
        Object s = new Studio();
        Setters.set(s, "name", "Main hall");
        Setters.set(s, "rooms", 3);
        assertTrue(v.validate(s).isEmpty());
        em.persist(s);
        em.flush();
        assertNotNull(getFieldValueReflexively(s, "id"), "The id must be generated by the inherited mapping");
        Setters.set(s, "rooms", 0);
        assertFalse(v.validate(s).isEmpty(), "A studio needs at least one room");
        Setters.set(s, "rooms", 3);
        Setters.set(s, "name", "Ab");
        assertFalse(v.validate(s).isEmpty(), "The inherited constraint of name (3-50 characters) must apply");
    }

}
